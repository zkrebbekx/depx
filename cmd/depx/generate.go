// Command depx generates a dependency-struct constructor from an annotated
// implementation struct: an exported Deps mirror, a constructor that wires the
// fields and validates them with depx.Validate, and a test-deps builder. This
// file holds the parse + emit core; main.go wires the CLI.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"sort"
	"strings"
)

// fieldSpec is one injected dependency.
type fieldSpec struct {
	ImplName string // unexported field on the impl struct, e.g. "db"
	DepsName string // exported field on the Deps struct, e.g. "DB"
	TypeStr  string // rendered type, e.g. "*sqlx.DB"
	Optional bool   // tagged depx:"optional"
}

// depsSpec is everything needed to emit the Deps boilerplate for one type.
type depsSpec struct {
	Package  string
	ImplType string // "factory"
	Exported string // "Factory"
	Return   string // constructor return type, e.g. "*factory" or "Factory"
	Fields   []fieldSpec
	Imports  map[string]string // alias -> path, for referenced field types
}

// parse reads Go source and builds a depsSpec for the named struct type.
// returnType overrides the constructor's return type ("" -> "*<type>").
func parse(filename string, src []byte, typeName, returnType string) (*depsSpec, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, filename, src, parser.ParseComments)
	if err != nil {
		return nil, fmt.Errorf("parse %s: %w", filename, err)
	}

	st, err := findStruct(file, typeName)
	if err != nil {
		return nil, err
	}

	srcImports := importsByName(file)
	spec := &depsSpec{
		Package:  file.Name.Name,
		ImplType: typeName,
		Exported: upperFirst(typeName),
		Return:   returnType,
		Imports:  map[string]string{},
	}
	if spec.Return == "" {
		spec.Return = "*" + typeName
	}

	for _, f := range st.Fields.List {
		if len(f.Names) == 0 {
			return nil, fmt.Errorf("type %s: embedded fields are not supported", typeName)
		}
		opts := parseTag(f.Tag)
		if opts.exclude {
			continue
		}
		typeStr := renderType(fset, f.Type)

		for _, name := range f.Names {
			depsName := opts.name
			if depsName == "" {
				depsName = upperFirst(name.Name)
			}
			spec.Fields = append(spec.Fields, fieldSpec{
				ImplName: name.Name,
				DepsName: depsName,
				TypeStr:  typeStr,
				Optional: opts.optional,
			})
		}

		for pkg := range referencedPackages(f.Type) {
			if path, ok := srcImports[pkg]; ok {
				spec.Imports[pkg] = path
			}
		}
	}

	if len(spec.Fields) == 0 {
		return nil, fmt.Errorf("type %s: no injectable fields found (all excluded or none present)", typeName)
	}
	return spec, nil
}

func findStruct(file *ast.File, typeName string) (*ast.StructType, error) {
	for _, decl := range file.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok || gd.Tok != token.TYPE {
			continue
		}
		for _, spec := range gd.Specs {
			ts, ok := spec.(*ast.TypeSpec)
			if !ok || ts.Name.Name != typeName {
				continue
			}
			st, ok := ts.Type.(*ast.StructType)
			if !ok {
				return nil, fmt.Errorf("type %s is not a struct", typeName)
			}
			return st, nil
		}
	}
	return nil, fmt.Errorf("type %s not found in source", typeName)
}

func importsByName(file *ast.File) map[string]string {
	out := map[string]string{}
	for _, imp := range file.Imports {
		path := strings.Trim(imp.Path.Value, `"`)
		name := path[strings.LastIndex(path, "/")+1:]
		if imp.Name != nil {
			name = imp.Name.Name
		}
		out[name] = path
	}
	return out
}

func referencedPackages(expr ast.Expr) map[string]struct{} {
	pkgs := map[string]struct{}{}
	ast.Inspect(expr, func(n ast.Node) bool {
		if sel, ok := n.(*ast.SelectorExpr); ok {
			if id, ok := sel.X.(*ast.Ident); ok {
				pkgs[id.Name] = struct{}{}
			}
		}
		return true
	})
	return pkgs
}

func renderType(fset *token.FileSet, expr ast.Expr) string {
	var b strings.Builder
	_ = printer.Fprint(&b, fset, expr)
	return b.String()
}

type tagOpts struct {
	exclude  bool
	optional bool
	name     string
}

// parseTag reads the depx struct tag: "-" excludes the field, "optional"
// marks it not required, "name=X" overrides the exported Deps field name.
func parseTag(tag *ast.BasicLit) tagOpts {
	var opts tagOpts
	if tag == nil {
		return opts
	}
	val := structTag(strings.Trim(tag.Value, "`")).get("depx")
	for _, part := range strings.Split(val, ",") {
		part = strings.TrimSpace(part)
		switch {
		case part == "-":
			opts.exclude = true
		case part == "optional":
			opts.optional = true
		case strings.HasPrefix(part, "name="):
			opts.name = strings.TrimPrefix(part, "name=")
		}
	}
	return opts
}

// generate renders the Deps struct, constructor, and test builder.
func generate(s *depsSpec) ([]byte, error) {
	deps := s.Exported + "Deps"

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by \"depx -type %s\"; DO NOT EDIT.\n\n", s.ImplType)
	fmt.Fprintf(&buf, "package %s\n\n", s.Package)

	fmt.Fprintf(&buf, "import (\n\t\"github.com/zkrebbekx/depx\"\n")
	var extra []string
	for _, path := range s.Imports {
		extra = append(extra, path)
	}
	sort.Strings(extra)
	for _, path := range extra {
		fmt.Fprintf(&buf, "\t%q\n", path)
	}
	buf.WriteString(")\n\n")

	// Deps struct.
	fmt.Fprintf(&buf, "// %s holds the dependencies of %s. Required fields are\n// checked by [New%s]; optional ones may be nil.\n", deps, s.ImplType, s.Exported)
	fmt.Fprintf(&buf, "type %s struct {\n", deps)
	for _, f := range s.Fields {
		if f.Optional {
			fmt.Fprintf(&buf, "\t%s %s `depx:\"optional\"`\n", f.DepsName, f.TypeStr)
		} else {
			fmt.Fprintf(&buf, "\t%s %s\n", f.DepsName, f.TypeStr)
		}
	}
	buf.WriteString("}\n\n")

	// Constructor.
	fmt.Fprintf(&buf, "// New%s validates d and returns a wired %s.\n", s.Exported, s.ImplType)
	fmt.Fprintf(&buf, "func New%s(d %s) (%s, error) {\n", s.Exported, deps, s.Return)
	buf.WriteString("\tif err := depx.Validate(d); err != nil {\n\t\treturn nil, err\n\t}\n")
	fmt.Fprintf(&buf, "\treturn &%s{\n", s.ImplType)
	for _, f := range s.Fields {
		fmt.Fprintf(&buf, "\t\t%s: d.%s,\n", f.ImplName, f.DepsName)
	}
	buf.WriteString("\t}, nil\n}\n\n")

	// Test-deps builder.
	fmt.Fprintf(&buf, "// NewTest%s builds a %s for tests, applying overrides over the\n// zero value so a test need only set the dependencies it cares about.\n", deps, deps)
	fmt.Fprintf(&buf, "func NewTest%s(overrides ...func(*%s)) %s {\n", deps, deps, deps)
	fmt.Fprintf(&buf, "\tvar d %s\n\tfor _, o := range overrides {\n\t\to(&d)\n\t}\n\treturn d\n}\n", deps)

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("gofmt generated source for %s: %w\n%s", s.ImplType, err, buf.String())
	}
	return formatted, nil
}

func upperFirst(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

// structTag is a tiny stand-in for reflect.StructTag to read a tag from the
// AST without building a reflect value.
type structTag string

func (t structTag) get(key string) string {
	s := string(t)
	for s != "" {
		i := 0
		for i < len(s) && s[i] == ' ' {
			i++
		}
		s = s[i:]
		if s == "" {
			break
		}
		i = 0
		for i < len(s) && s[i] != ':' && s[i] != ' ' && s[i] != '"' {
			i++
		}
		if i == 0 || i+1 >= len(s) || s[i] != ':' || s[i+1] != '"' {
			break
		}
		name := s[:i]
		s = s[i+2:]
		i = 0
		for i < len(s) && s[i] != '"' {
			if s[i] == '\\' {
				i++
			}
			i++
		}
		if i >= len(s) {
			break
		}
		value := s[:i]
		s = s[i+1:]
		if name == key {
			return value
		}
	}
	return ""
}
