package main

import (
	"regexp"
	"testing"

	. "github.com/smartystreets/goconvey/convey"
)

// flatten collapses runs of whitespace to a single space so assertions need
// not track gofmt's column alignment.
var wsRun = regexp.MustCompile(`[ \t]+`)

func flatten(s string) string { return wsRun.ReplaceAllString(s, " ") }

const factorySrc = `package notification

import "time"

type factory struct {
	db          DB
	profileAuth CurrentProfileFunc
	templates   Registry  ` + "`depx:\"name=Templates\"`" + `
	enricher    Enricher  ` + "`depx:\"optional\"`" + `
	createdAt   time.Time ` + "`depx:\"-\"`" + `
}
`

func TestParse(t *testing.T) {
	Convey("Given an annotated implementation struct", t, func() {
		spec, err := parse("factory.go", []byte(factorySrc), "factory", "Factory")
		So(err, ShouldBeNil)

		Convey("Then package, type, and return are read", func() {
			So(spec.Package, ShouldEqual, "notification")
			So(spec.ImplType, ShouldEqual, "factory")
			So(spec.Exported, ShouldEqual, "Factory")
			So(spec.Return, ShouldEqual, "Factory")
		})

		Convey("Then excluded fields are dropped and others kept", func() {
			var names []string
			for _, f := range spec.Fields {
				names = append(names, f.DepsName)
			}
			So(names, ShouldResemble, []string{"Db", "ProfileAuth", "Templates", "Enricher"})
		})

		Convey("Then name= overrides the exported field name", func() {
			So(spec.Fields[2].ImplName, ShouldEqual, "templates")
			So(spec.Fields[2].DepsName, ShouldEqual, "Templates")
		})

		Convey("Then optional is recorded", func() {
			So(spec.Fields[3].DepsName, ShouldEqual, "Enricher")
			So(spec.Fields[3].Optional, ShouldBeTrue)
			So(spec.Fields[0].Optional, ShouldBeFalse)
		})
	})

	Convey("Given no return override", t, func() {
		spec, err := parse("f.go", []byte(factorySrc), "factory", "")
		Convey("Then the return type defaults to a pointer to the impl", func() {
			So(err, ShouldBeNil)
			So(spec.Return, ShouldEqual, "*factory")
		})
	})

	Convey("Given a missing type", t, func() {
		_, err := parse("f.go", []byte(factorySrc), "nope", "")
		Convey("Then it errors", func() {
			So(err, ShouldNotBeNil)
			So(err.Error(), ShouldContainSubstring, "not found")
		})
	})
}

func TestGenerate(t *testing.T) {
	Convey("Given a parsed factory spec", t, func() {
		spec, err := parse("factory.go", []byte(factorySrc), "factory", "Factory")
		So(err, ShouldBeNil)

		Convey("When generated", func() {
			out, err := generate(spec)
			So(err, ShouldBeNil)
			code := string(out)
			flat := flatten(code)

			Convey("Then it is valid gofmt'd Go with the DO NOT EDIT header", func() {
				So(code, ShouldStartWith, "// Code generated by")
				So(code, ShouldContainSubstring, "package notification")
			})

			Convey("Then the Deps struct mirrors included fields", func() {
				So(code, ShouldContainSubstring, "type FactoryDeps struct")
				So(flat, ShouldContainSubstring, "Templates Registry")
				So(flat, ShouldContainSubstring, "Enricher Enricher `depx:\"optional\"`")
				So(code, ShouldNotContainSubstring, "createdAt")
			})

			Convey("Then the constructor validates and wires field by field", func() {
				So(flat, ShouldContainSubstring, "func NewFactory(d FactoryDeps) (Factory, error)")
				So(code, ShouldContainSubstring, "if err := depx.Validate(d); err != nil")
				So(flat, ShouldContainSubstring, "templates: d.Templates,")
			})

			Convey("Then a test-deps builder is emitted", func() {
				So(flat, ShouldContainSubstring, "func NewTestFactoryDeps(overrides ...func(*FactoryDeps)) FactoryDeps")
			})
		})
	})
}

func TestImportsCarried(t *testing.T) {
	Convey("Given a struct with a cross-package field type", t, func() {
		src := `package svc
import "database/sql"
type svc struct {
	db *sql.DB
}`
		spec, err := parse("svc.go", []byte(src), "svc", "")
		So(err, ShouldBeNil)

		Convey("When generated", func() {
			out, err := generate(spec)
			So(err, ShouldBeNil)

			Convey("Then the field-type import is carried through", func() {
				So(string(out), ShouldContainSubstring, `"database/sql"`)
				So(string(out), ShouldContainSubstring, "Db *sql.DB")
			})
		})
	})
}

func TestExcludedOnlyErrors(t *testing.T) {
	Convey("Given a struct whose only field is excluded", t, func() {
		src := "package p\ntype p struct {\n\tx int `depx:\"-\"`\n}"
		_, err := parse("p.go", []byte(src), "p", "")
		Convey("Then it errors that there is nothing to inject", func() {
			So(err, ShouldNotBeNil)
			So(err.Error(), ShouldContainSubstring, "no injectable fields")
		})
	})
}
